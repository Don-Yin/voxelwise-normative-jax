"""Nested IXI references, fixed held-outs and independent synthetic voxel generators."""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .artifacts import PCNTOOLKIT_REFERENCE, VOXEL_MATRIX, resolve
from .basis import Basis
from .batch_job import require_batch_job
from .cohort import IXI_SITES, ixi_covariates, load_covariates, pinned_agreement, site_split
from .reference_grid import CHAINS, COLUMNS_SEED, MASK_VOXELS, N_HELD_OUT, SYNTHETIC_SEED, Cell


@dataclass(frozen=True)
class Reference:
    """The converged PCNtoolkit scores on a frozen, random mask sample."""

    voxels: np.ndarray
    z: np.ndarray

    def max_delta(self, voxels: np.ndarray, z: np.ndarray) -> float:
        """Maximum absolute difference in the overlap with the frozen sample."""
        positions = np.flatnonzero(np.isin(voxels, self.voxels))
        if not len(positions):
            raise ValueError("cannot check z agreement: no sampled voxels overlap the frozen reference")
        expected = self.z[:, np.searchsorted(self.voxels, voxels[positions])]
        return float(np.abs(z[:, positions] - expected).max())


@dataclass(frozen=True)
class Cohort:
    """Real memory-mapped inputs or synthetic inputs generated by absolute voxel index."""

    x: np.ndarray
    sites: np.ndarray
    train: np.ndarray
    test: np.ndarray
    gm: np.ndarray | None
    reference: Reference | None = None
    synthetic_mean: np.ndarray | None = None

    def basis(self) -> Basis:
        """Fit the design scaling and spline knots without the held-out people."""
        return Basis.fit(self.x[self.train], self.sites[self.train], batch_levels=IXI_SITES)

    def responses(self, train: np.ndarray, voxels: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """Return raw train/test tiles for the same ordered mask columns."""
        if self.gm is not None:
            return self.gm[np.ix_(train, voxels)], self.gm[np.ix_(self.test, voxels)]
        if self.synthetic_mean is None:
            raise ValueError("synthetic source has no design mean")
        n = len(self.synthetic_mean)
        raw = np.empty((len(voxels), n), dtype=np.float32)
        for i, col in enumerate(voxels):
            rng = np.random.default_rng([SYNTHETIC_SEED, int(col)])
            offset, scale = rng.uniform(-0.04, 0.04), rng.uniform(0.035, 0.080)
            noise = rng.standard_normal(n, dtype=np.float32)
            raw[i] = self.synthetic_mean + offset + scale * noise
        return raw[:, train].T, raw[:, self.test].T


def mask_sample(width: int) -> np.ndarray:
    """Prefixes of one shuffled pool from exp_002's 1,000 uniformly sampled voxels."""
    if not 1 <= width <= 1000:
        raise ValueError(f"CPU sample width must be in 1..1000, not {width}")
    pool = np.sort(np.random.default_rng(0).choice(MASK_VOXELS, 1000, replace=False))
    return np.sort(np.random.default_rng(COLUMNS_SEED).permutation(pool)[:width])


def nested_train(sites: np.ndarray, eligible: np.ndarray, n: int, seed: int) -> np.ndarray:
    """Advance a site-balanced random priority list; every size includes the earlier rows."""
    if not len(IXI_SITES) <= n <= len(eligible) or set(sites[eligible]) != set(IXI_SITES):
        raise ValueError(f"invalid training size or sites: {n=}, eligible={len(eligible)}, {set(sites[eligible])}")
    rng = np.random.default_rng(seed)
    by_site = [rng.permutation(eligible[sites[eligible] == site]) for site in IXI_SITES]
    sizes = np.asarray([len(rows) for rows in by_site])
    picked = np.zeros_like(sizes)
    rows = []
    for i in range(1, n + 1):
        deficit = i * sizes / sizes.sum() - picked
        site = int(np.argmax(np.where(picked < sizes, deficit, -np.inf)))
        rows.append(by_site[site][picked[site]])
        picked[site] += 1
    if not np.all(picked):
        raise ValueError(f"reference N={n} lacks a site: {picked.tolist()}")
    return np.sort(np.asarray(rows))


def bootstrap_draw(cohort: Cohort, rng: np.random.Generator) -> np.ndarray:
    """Resample paired reference rows with replacement at fixed site counts."""
    sites = cohort.sites[cohort.train]
    groups = [cohort.train[sites == site] for site in IXI_SITES]
    return rng.permutation(np.concatenate([rng.choice(rows, size=len(rows), replace=True) for rows in groups]))


def real_cohort(n: int, chain: int) -> Cohort:
    """Bind the real matrix and verified held-out split without saving any rows."""
    require_batch_job("real IXI input")
    gm_path = resolve(VOXEL_MATRIX, "gm.npy")["gm.npy"]
    gm = np.load(gm_path, mmap_mode="r", allow_pickle=False)
    if gm.shape != (563, MASK_VOXELS) or gm.dtype != np.float32:
        raise ValueError(f"unexpected IXI matrix {gm_path}: {gm.shape=}, {gm.dtype=}")
    cov = load_covariates()
    with np.load(resolve(PCNTOOLKIT_REFERENCE, "arrays.npz")["arrays.npz"], allow_pickle=False) as pinned:
        test = pinned["test"]
        if test.dtype != bool or test.shape != (563,) or not np.array_equal(test, site_split(cov["site"], 0)):
            raise ValueError(f"frozen IXI hold-out does not match the 563-row site split: {test.shape=}, {test.dtype=}")
        pinned_agreement(cov, pinned)
        if n == 450:
            ref = Reference(pinned["voxels"], pinned["z_test"])
            if (ref.z.shape != (N_HELD_OUT, 1000) or not np.isfinite(ref.z).all()
                    or np.any(np.diff(ref.voxels) <= 0) or not np.isin(mask_sample(1000), ref.voxels).all()):
                raise ValueError("invalid frozen PCNtoolkit reference voxel sample or scores")
        else:
            ref = None
    held = np.flatnonzero(test)
    if len(held) != N_HELD_OUT:
        raise ValueError(f"expected {N_HELD_OUT} fixed IXI hold-outs, got {len(held)}")
    train = nested_train(cov["site"], np.flatnonzero(~test), n, CHAINS[chain])
    return Cohort(ixi_covariates(cov), cov["site"], train, held, gm, ref)


def synthetic_cohort(n: int, held_out: int = N_HELD_OUT) -> Cohort:
    """Nested artificial cohorts: ages, sex, three sites and voxel-specific noise."""
    total = n + held_out
    age = np.random.default_rng([SYNTHETIC_SEED, 1]).uniform(20.0, 86.0, total)
    male = np.random.default_rng([SYNTHETIC_SEED, 2]).random(total) < 0.5
    site = np.resize(np.asarray(IXI_SITES), total)
    mean = (0.5 - 0.003 * (age - 50) + 0.02 * male
            + 0.012 * (site == IXI_SITES[0]) - 0.015 * (site == IXI_SITES[2])).astype(np.float32)
    return Cohort(np.column_stack((age, male)), site, np.arange(held_out, total),
                  np.arange(held_out), None, synthetic_mean=mean)


def load_cohort(cell: Cell, chain: int = 0) -> Cohort:
    """Resolve the cell's authorized source."""
    return real_cohort(cell.n, chain) if cell.dataset == "ixi" else synthetic_cohort(cell.n)
